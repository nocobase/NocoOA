import { attachmentSelectionFilters } from '../attachment-selection.js';
import { AssetError } from '../../providers/assets/errors.js';
import {
  authenticationToken,
  type AuthEnv,
} from '@nocobase/app-plugin-authentication';
import {
  authorizationToken,
  type AuthorizationEnv,
} from '@nocobase/app-plugin-authorization/server';
import { defineFileRepositoryApiRoutes } from '@nocobase/app-plugin-file/server';
import { databaseManagerToken } from '@nocobase/db';
import type { Application } from '@nocobase/app-server/application';
import {
  ApiError,
  apiErrorHandler,
  apiValidator,
  type AppRouteContribution,
} from '@nocobase/app-server/router';
import { Hono, type Context } from 'hono';
import { i18nToken } from '@nocobase/app-server/i18n';
import { getRequestLocale } from '@nocobase/i18n/server';
import { bodyLimit } from 'hono/body-limit';
import { z } from 'zod';
import {
  assetPhotoServiceToken,
  ASSET_PHOTO_FIELDS,
  MAX_ASSET_PHOTO_SIZE,
  validateAssetPhoto,
} from '../../providers/asset-requests/attachments.js';

type Env = AuthEnv & AuthorizationEnv;
interface Principal {
  requestId: string;
  actorId: string;
  version: number;
  ids?: string[];
  upload: boolean;
}
const principals = new WeakMap<object, Principal>();
const generated = defineFileRepositoryApiRoutes<Principal>({
  principal: (c) => principals.get(c)!,
  repositories: [
    {
      name: 'assetRequestPhotos',
      collection: 'assetRequestPhotos',
      disk: 'local',
      accessPath: '/uploads/asset-requests',
      accessMode: 'stream',
      policy: (p) => ({
        read: {
          scope: (f) =>
            f.and([
              f.string('requestId').eq(p.requestId),
              ...attachmentSelectionFilters(f, p.ids),
            ]),
          fields: ASSET_PHOTO_FIELDS,
        },
        create: p.upload
          ? {
              scope: { requestId: p.requestId, ownerId: p.actorId },
              defaults: {
                requestId: p.requestId,
                ownerId: p.actorId,
                uploadVersion: p.version,
              },
            }
          : false,
        update: false,
        delete: false,
      }),
      actions: {
        findMany: { maxLimit: 10 },
        findOne: {},
        uploadOne: { maxSize: MAX_ASSET_PHOTO_SIZE + 65536 },
      },
    },
  ],
});

/** Export only these guarded contributions; the generated byte routes are public until wrapped. */
export const routes: readonly AppRouteContribution<Application>[] =
  generated.map((contribution) => ({
    scope: contribution.scope,
    createRouter: async (app: Application) => {
      const router = new Hono<Env>();
      const path =
        contribution.scope === 'api'
          ? '/assetRequestPhotos/*'
          : '/uploads/asset-requests/*';
      const auth = app.container.resolve(authenticationToken);
      const authz = app.container.resolve(authorizationToken);
      const db = app.container.resolve(databaseManagerToken);
      const service = app.container.resolve(assetPhotoServiceToken);
      const i18n = app.container.resolve(i18nToken);
      const errorHandler = async (error: Error, ctx: Context) => {
        if (!(error instanceof AssetError)) return apiErrorHandler(error, ctx);
        const locale = getRequestLocale(ctx) ?? i18n.getDefaultLocale();
        await i18n.ensureLocaleLoaded(locale);
        const message = i18n.getFixedT('nb3-oa', locale)(
          `assetRequests.errors.${error.code}`,
          { defaultValue: error.message },
        );
        return apiErrorHandler(
          new ApiError({
            status:
              error.code === 'ASSET_PHOTO_DENIED'
                ? 'PERMISSION_DENIED'
                : 'INVALID_ARGUMENT',
            domain: 'assetRequests',
            reason: error.code,
            message: error.message,
            localizedMessage: { locale, message },
            metadata: {
              ns: 'nb3-oa',
              key: `assetRequests.errors.${error.code}`,
            },
            cause: error,
          }),
          ctx,
        );
      };
      router.onError(errorHandler);
      router.use(path, auth.required(), authz.middleware());
      if (contribution.scope === 'api')
        router.use(
          path,
          apiValidator(
            'header',
            z.object({
              'x-asset-request-id': z
                .string()
                .regex(/^[A-Za-z0-9_-]{1,64}$/)
                .describe(
                  'Owning asset request draft or request. All uploads and reads enforce its business permissions.',
                ),
            }),
          ),
        );
      router.use(path, async (c, next) => {
        const actorId = c.get('auth')!.user.id;
        const upload =
          contribution.scope === 'api' && c.req.path.endsWith('/uploadOne');
        let requestId = c.req.header('x-asset-request-id');
        let fileId: string | undefined;
        if (contribution.scope === 'root') {
          fileId = c.req.path.split('/').at(-1)?.split('.')[0];
          const file = fileId
            ? await db
                .repository<{ id: string; requestId: string }>(
                  'assetRequestPhotos',
                )
                .findOne({ filter: { id: fileId } })
            : undefined;
          if (!file)
            throw new AssetError(
              'ASSET_PHOTO_DENIED',
              'The attachment is not accessible.',
            );
          requestId = file.requestId;
        }
        if (!requestId || !/^[A-Za-z0-9_-]{1,64}$/.test(requestId))
          throw new AssetError(
            'ASSET_PHOTO_INVALID',
            'x-asset-request-id must identify the owning draft or request.',
          );
        const decision = await c.get('authz').authorize({
          resource: { type: 'composite', id: 'oa.assetRequests' },
          action: 'view',
        });
        const policy =
          decision.effect !== 'deny'
            ? decision.conditions?.database?.assetRequests
            : undefined;
        if (!policy)
          throw new AssetError(
            'ASSET_PHOTO_DENIED',
            'No asset request reading permission is granted.',
          );
        const record = await service.authorize(
          requestId,
          actorId,
          policy,
          upload,
        );
        if (upload) {
          const action = 'edit';
          const write = await c.get('authz').authorize({
            resource: { type: 'composite', id: 'oa.assetRequests' },
            action,
          });
          const writePolicy =
            write.effect !== 'deny'
              ? write.conditions?.database?.assetRequests
              : undefined;
          const update = writePolicy?.update;
          const writable =
            writePolicy &&
            update &&
            (update === true ||
              (Array.isArray(update.fields) &&
                update.fields.includes('photos')))
              ? await db
                  .repository('assetRequests')
                  .withPolicy({
                    ...writePolicy,
                    read:
                      update === true
                        ? true
                        : { scope: update.scope, fields: ['id'] },
                  })
                  .findOne({ filter: { id: requestId } })
              : undefined;
          if (!writePolicy || writePolicy.update === false || !writable)
            throw new AssetError(
              'ASSET_PHOTO_DENIED',
              'No asset request submission permission covers this draft.',
            );
        }
        // Unselected draft uploads are visible only to the people editing that draft. After submit,
        // participants may access only the immutable document's selected attachment IDs.
        const ids =
          ['draft', 'revision', 'exception'].includes(record.status) &&
          record.applicantId === actorId
            ? undefined
            : record.photos;
        if (fileId && ids && !ids.includes(fileId))
          throw new AssetError(
            'ASSET_PHOTO_DENIED',
            'This attachment is not linked to the submitted asset request request.',
          );
        principals.set(c, {
          requestId,
          actorId,
          version: record.lifecycleVersion,
          upload,
          ids,
        });
        await next();
      });
      if (contribution.scope === 'api') {
        // Limit before validation. Inspect a clone so the generated handler keeps its own
        // multipart parser and body limiter; consuming Hono's request first locks its stream.
        router.use(
          '/assetRequestPhotos/uploadOne',
          bodyLimit({
            maxSize: MAX_ASSET_PHOTO_SIZE + 65536,
            onError: () => {
              throw new AssetError(
                'ASSET_PHOTO_SIZE',
                'Attachment request is too large.',
              );
            },
          }),
        );
        router.use('/assetRequestPhotos/uploadOne', async (c, next) => {
          const body = await c.req.raw.clone().formData();
          const files = body.getAll('file');
          if (files.length !== 1 || !(files[0] instanceof File))
            throw new AssetError(
              'ASSET_PHOTO_INVALID',
              'Exactly one file is required.',
            );
          await validateAssetPhoto(files[0]);
          await next();
        });
      }
      const generatedRouter = await contribution.createRouter(app);
      generatedRouter.onError(errorHandler);
      router.route('/', generatedRouter);
      const root = new Hono();
      root.route('/', router);
      return root;
    },
  }));
export default routes;
