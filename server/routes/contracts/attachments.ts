import { attachmentSelectionFilters } from '../attachment-selection.js';
import { localizedContractError } from './localization.js';
import {
  authenticationToken,
  type AuthEnv,
} from '@nocobase/app-plugin-authentication';
import {
  authorizationToken,
  type AuthorizationEnv,
} from '@nocobase/app-plugin-authorization/server';
import { defineFileRepositoryApiRoutes } from '@nocobase/app-plugin-file/server';
import { databaseManagerToken } from '@nocobase/db';
import type { Application } from '@nocobase/app-server/application';
import {
  ApiError,
  apiErrorHandler,
  apiValidator,
  type AppRouteContribution,
} from '@nocobase/app-server/router';
import { Hono } from 'hono';
import { bodyLimit } from 'hono/body-limit';
import { z } from 'zod';
import {
  contractAttachmentServiceToken,
  ContractAttachmentError,
  CONTRACT_FILE_FIELDS,
  MAX_CONTRACT_FILE_SIZE,
  validateContractFile,
} from '../../providers/contracts/attachments.js';

type Env = AuthEnv & AuthorizationEnv;
interface Principal {
  requestId: string;
  actorId: string;
  version: number;
  ids?: readonly string[];
  upload: boolean;
  purpose: 'text' | 'evidence';
}
const principals = new WeakMap<object, Principal>();
const generated = defineFileRepositoryApiRoutes<Principal>({
  principal: (c) => principals.get(c)!,
  repositories: [
    {
      name: 'contractAttachments',
      collection: 'contractAttachmentFiles',
      disk: 'local',
      accessPath: '/uploads/contract',
      accessMode: 'stream',
      policy: (p) => ({
        read: {
          scope: (f) =>
            f.and([
              f.string('requestId').eq(p.requestId),
              f.string('purpose').eq(p.purpose),
              ...attachmentSelectionFilters(f, p.ids),
            ]),
          fields: CONTRACT_FILE_FIELDS,
        },
        create: p.upload
          ? {
              scope: {
                requestId: p.requestId,
                ownerId: p.actorId,
                purpose: p.purpose,
              },
              defaults: {
                requestId: p.requestId,
                ownerId: p.actorId,
                uploadVersion: p.version,
                purpose: p.purpose,
              },
            }
          : false,
        update: false,
        delete: false,
      }),
      actions: {
        findMany: { maxLimit: 10 },
        findOne: {},
        uploadOne: { maxSize: MAX_CONTRACT_FILE_SIZE + 65536 },
      },
    },
  ],
});

/** Export only these guarded contributions; the generated byte routes are public until wrapped. */
export const routes: readonly AppRouteContribution<Application>[] =
  generated.map((contribution) => ({
    scope: contribution.scope,
    createRouter: async (app: Application) => {
      const router = new Hono<Env>();
      const path =
        contribution.scope === 'api'
          ? '/contractAttachments/*'
          : '/uploads/contract/*';
      const auth = app.container.resolve(authenticationToken);
      const authz = app.container.resolve(authorizationToken);
      const db = app.container.resolve(databaseManagerToken);
      const service = app.container.resolve(contractAttachmentServiceToken);
      router.onError(async (error, c) =>
        apiErrorHandler(
          error instanceof ContractAttachmentError
            ? new ApiError({
                status:
                  error.code === 'CONTRACT_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : 'INVALID_ARGUMENT',
                domain: 'contract',
                reason: error.code,
                message: error.message,
                localizedMessage: await localizedContractError(
                  app,
                  c,
                  error.code,
                  error.message,
                ),
                metadata: {
                  ns: 'nb3-oa',
                  key: `contracts.errors.${error.code}`,
                },
              })
            : error,
          c,
        ),
      );
      router.use(path, auth.required(), authz.middleware());
      if (contribution.scope === 'api')
        router.use(
          path,
          apiValidator(
            'header',
            z.object({
              'x-contract-file-purpose': z
                .enum(['text', 'evidence'])
                .optional(),
              'x-contract-request-id': z
                .string()
                .regex(/^[A-Za-z0-9_-]{1,64}$/)
                .describe(
                  'Owning contract draft or request. All uploads and reads enforce its business permissions.',
                ),
            }),
          ),
        );
      router.use(path, async (c, next) => {
        const actorId = c.get('auth')!.user.id;
        const upload =
          contribution.scope === 'api' && c.req.path.endsWith('/uploadOne');
        let requestId = c.req.header('x-contract-request-id');
        let fileId: string | undefined;
        let purpose: 'text' | 'evidence' =
          c.req.header('x-contract-file-purpose') === 'text'
            ? 'text'
            : 'evidence';
        if (contribution.scope === 'root') {
          fileId = c.req.path.split('/').at(-1)?.split('.')[0];
          const file = fileId
            ? await db
                .repository<{
                  id: string;
                  requestId: string;
                  purpose: 'text' | 'evidence';
                }>('contractAttachmentFiles')
                .findOne({ filter: { id: fileId } })
            : undefined;
          if (!file)
            throw new ContractAttachmentError(
              'CONTRACT_ATTACHMENT_DENIED',
              'The attachment is not accessible.',
            );
          requestId = file.requestId;
          purpose = file.purpose;
        }
        if (!requestId || !/^[A-Za-z0-9_-]{1,64}$/.test(requestId))
          throw new ContractAttachmentError(
            'CONTRACT_ATTACHMENT_INVALID',
            'x-contract-request-id must identify the owning draft or request.',
          );
        const decision = await c.get('authz').authorize({
          resource: { type: 'composite', id: 'oa.contract' },
          action: 'view',
        });
        const policy =
          decision.effect !== 'deny'
            ? decision.conditions?.database?.contractRequests
            : undefined;
        if (!policy)
          throw new ContractAttachmentError(
            'CONTRACT_ATTACHMENT_DENIED',
            'No contract application reading permission is granted.',
          );
        const record = await service.authorize(
          requestId,
          actorId,
          policy,
          upload,
          purpose,
        );
        if (upload) {
          const action = 'submit';
          const write = await c.get('authz').authorize({
            resource: { type: 'composite', id: 'oa.contract' },
            action,
          });
          const writePolicy =
            write.effect !== 'deny'
              ? write.conditions?.database?.contractRequests
              : undefined;
          const update = writePolicy?.update;
          const writable =
            writePolicy &&
            update &&
            (update === true ||
              (Array.isArray(update.fields) &&
                update.fields.includes(
                  purpose === 'text' ? 'textVersionId' : 'attachments',
                )))
              ? await db
                  .repository('contractRequests')
                  .withPolicy({
                    ...writePolicy,
                    read:
                      update === true
                        ? true
                        : { scope: update.scope, fields: ['id'] },
                  })
                  .findOne({ filter: { id: requestId } })
              : undefined;
          if (!writePolicy || writePolicy.update === false || !writable)
            throw new ContractAttachmentError(
              'CONTRACT_ATTACHMENT_DENIED',
              'No contract application submission permission covers this draft.',
            );
        }
        // Unselected draft uploads are visible only to the people editing that draft. After submit,
        // participants may access only the immutable document's selected attachment IDs.
        const ids =
          ['draft', 'revision'].includes(record.status) &&
          [record.applicantId, record.creatorId].includes(actorId)
            ? undefined
            : purpose === 'evidence'
              ? record.attachments
              : (
                  await db.repository('contractTextVersions').findMany({
                    filter: {
                      requestId,
                      ...(record.textVersionId
                        ? { id: record.textVersionId }
                        : { id: 'missing' }),
                    },
                  })
                ).map((v) =>
                  typeof v.fileId === 'string' ? v.fileId : 'invalid',
                );
        if (fileId && ids && !ids.includes(fileId))
          throw new ContractAttachmentError(
            'CONTRACT_ATTACHMENT_DENIED',
            'This attachment is not linked to the submitted contract application.',
          );
        principals.set(c, {
          requestId,
          actorId,
          version: record.lifecycleVersion,
          upload,
          ids,
          purpose,
        });
        await next();
      });
      if (contribution.scope === 'api') {
        // Limit before validation. Inspect a clone so the generated handler keeps its own
        // multipart parser and body limiter; consuming Hono's request first locks its stream.
        router.use(
          '/contractAttachments/uploadOne',
          bodyLimit({
            maxSize: MAX_CONTRACT_FILE_SIZE + 65536,
            onError: () => {
              throw new ContractAttachmentError(
                'CONTRACT_FILE_SIZE',
                'Attachment request is too large.',
              );
            },
          }),
        );
        router.use('/contractAttachments/uploadOne', async (c, next) => {
          const body = await c.req.raw.clone().formData();
          const files = body.getAll('file');
          if (files.length !== 1 || !(files[0] instanceof File))
            throw new ContractAttachmentError(
              'CONTRACT_ATTACHMENT_INVALID',
              'Exactly one file is required.',
            );
          if (
            c.req.header('x-contract-file-purpose') === 'text' &&
            (files[0].type !== 'application/pdf' ||
              !files[0].name.toLowerCase().endsWith('.pdf'))
          )
            throw new ContractAttachmentError(
              'CONTRACT_FILE_TYPE',
              'Immutable contract text must be a PDF.',
            );
          await validateContractFile(files[0]);
          await next();
        });
      }
      const generatedRouter = await contribution.createRouter(app);
      generatedRouter.onError(async (error, c) =>
        apiErrorHandler(
          error instanceof ContractAttachmentError
            ? new ApiError({
                status:
                  error.code === 'CONTRACT_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : 'INVALID_ARGUMENT',
                domain: 'contract',
                reason: error.code,
                message: error.message,
                localizedMessage: await localizedContractError(
                  app,
                  c,
                  error.code,
                  error.message,
                ),
                metadata: {
                  ns: 'nb3-oa',
                  key: `contracts.errors.${error.code}`,
                },
              })
            : error,
          c,
        ),
      );
      router.route('/', generatedRouter);
      const root = new Hono();
      root.route('/', router);
      return root;
    },
  }));
export default routes;
