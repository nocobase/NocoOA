import { attachmentSelectionFilters } from '../attachment-selection.js';
import {
  authenticationToken,
  type AuthEnv,
} from '@nocobase/app-plugin-authentication';
import {
  authorizationToken,
  type AuthorizationEnv,
} from '@nocobase/app-plugin-authorization/server';
import { defineFileRepositoryApiRoutes } from '@nocobase/app-plugin-file/server';
import { databaseManagerToken } from '@nocobase/db';
import type { Application } from '@nocobase/app-server/application';
import {
  ApiError,
  apiErrorHandler,
  apiValidator,
  type AppRouteContribution,
} from '@nocobase/app-server/router';
import { Hono } from 'hono';
import { bodyLimit } from 'hono/body-limit';
import { z } from 'zod';
import {
  paymentAttachmentServiceToken,
  PaymentAttachmentError,
  PAYMENT_FILE_FIELDS,
  MAX_PAYMENT_FILE_SIZE,
  validatePaymentFile,
} from '../../providers/payment-requests/attachments.js';

type Env = AuthEnv & AuthorizationEnv;
interface Principal {
  paymentRequestId: string;
  actorId: string;
  version: number;
  ids?: string[];
  upload: boolean;
  purpose: 'invoice' | 'voucher';
}
const principals = new WeakMap<object, Principal>();
const generated = defineFileRepositoryApiRoutes<Principal>({
  principal: (c) => principals.get(c)!,
  repositories: [
    {
      name: 'paymentAttachments',
      collection: 'paymentAttachmentFiles',
      disk: 'local',
      accessPath: '/uploads/payment',
      accessMode: 'stream',
      policy: (p) => ({
        read: {
          scope: (f) =>
            f.and([
              f.string('paymentRequestId').eq(p.paymentRequestId),
              f.string('purpose').eq(p.purpose),
              ...attachmentSelectionFilters(f, p.ids),
            ]),
          fields: PAYMENT_FILE_FIELDS,
        },
        create: p.upload
          ? {
              scope: {
                paymentRequestId: p.paymentRequestId,
                ownerId: p.actorId,
                purpose: p.purpose,
              },
              defaults: {
                paymentRequestId: p.paymentRequestId,
                purpose: p.purpose,
                ownerId: p.actorId,
                sourceVersion: p.version,
              },
            }
          : false,
        update: false,
        delete: false,
      }),
      actions: {
        findMany: { maxLimit: 100 },
        findOne: {},
        uploadOne: { maxSize: MAX_PAYMENT_FILE_SIZE + 65536 },
      },
    },
  ],
});

/** Export only these guarded contributions; the generated byte routes are public until wrapped. */
export const routes: readonly AppRouteContribution<Application>[] =
  generated.map((contribution) => ({
    scope: contribution.scope,
    createRouter: async (app: Application) => {
      const router = new Hono<Env>();
      const path =
        contribution.scope === 'api'
          ? '/paymentAttachments/*'
          : '/uploads/payment/*';
      const auth = app.container.resolve(authenticationToken);
      const authz = app.container.resolve(authorizationToken);
      const db = app.container.resolve(databaseManagerToken);
      const service = app.container.resolve(paymentAttachmentServiceToken);
      router.onError((error, c) =>
        apiErrorHandler(
          error instanceof PaymentAttachmentError
            ? new ApiError({
                status:
                  error.code === 'PAYMENT_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : 'INVALID_ARGUMENT',
                domain: 'payment',
                reason: error.code,
                message: error.message,
              })
            : error,
          c,
        ),
      );
      router.use(path, auth.required(), authz.middleware());
      if (contribution.scope === 'api')
        router.use(
          path,
          apiValidator(
            'header',
            z.object({
              'x-payment-file-purpose': z
                .enum(['invoice', 'voucher'])
                .default('invoice'),
              'x-payment-request-id': z
                .string()
                .regex(/^[A-Za-z0-9_-]{1,64}$/)
                .describe(
                  'Owning payment draft or request. All uploads and reads enforce its business permissions.',
                ),
            }),
          ),
        );
      router.use(path, async (c, next) => {
        const actorId = c.get('auth')!.user.id;
        const upload =
          contribution.scope === 'api' && c.req.path.endsWith('/uploadOne');
        let purpose: 'invoice' | 'voucher' =
          c.req.header('x-payment-file-purpose') === 'voucher'
            ? 'voucher'
            : 'invoice';
        let paymentRequestId = c.req.header('x-payment-request-id');
        let fileId: string | undefined;
        if (contribution.scope === 'root') {
          fileId = c.req.path.split('/').at(-1)?.split('.')[0];
          const file = fileId
            ? await db
                .repository<{
                  id: string;
                  paymentRequestId: string;
                  purpose: 'invoice' | 'voucher';
                }>('paymentAttachmentFiles')
                .findOne({ filter: { id: fileId } })
            : undefined;
          if (!file)
            throw new PaymentAttachmentError(
              'PAYMENT_ATTACHMENT_DENIED',
              'The attachment is not accessible.',
            );
          paymentRequestId = file.paymentRequestId;
          purpose = file.purpose;
        }
        if (
          !paymentRequestId ||
          !/^[A-Za-z0-9_-]{1,64}$/.test(paymentRequestId)
        )
          throw new PaymentAttachmentError(
            'PAYMENT_ATTACHMENT_INVALID',
            'x-payment-request-id must identify the owning draft or request.',
          );
        const decision = await c.get('authz').authorize({
          resource: { type: 'composite', id: 'oa.payment' },
          action: 'view',
        });
        const policy =
          decision.effect !== 'deny'
            ? decision.conditions?.database?.paymentRequests
            : undefined;
        if (!policy)
          throw new PaymentAttachmentError(
            'PAYMENT_ATTACHMENT_DENIED',
            'No payment reading permission is granted.',
          );
        const record = await service.authorize(
          paymentRequestId,
          actorId,
          policy,
          upload,
          purpose,
        );
        if (upload) {
          const action =
            purpose === 'voucher'
              ? 'voucherEvidence'
              : record.applicantId === actorId
                ? 'submit'
                : 'delegate';
          const write = await c.get('authz').authorize({
            resource: { type: 'composite', id: 'oa.payment' },
            action,
          });
          const writePolicy =
            write.effect !== 'deny'
              ? write.conditions?.database?.paymentRequests
              : undefined;
          const update = writePolicy?.update;
          const writable =
            writePolicy &&
            update &&
            (update === true ||
              (Array.isArray(update.fields) &&
                update.fields.includes(
                  purpose === 'invoice' ? 'attachments' : 'voucherAttachments',
                )))
              ? await db
                  .repository('paymentRequests')
                  .withPolicy({
                    ...writePolicy,
                    read:
                      update === true
                        ? true
                        : { scope: update.scope, fields: ['id'] },
                  })
                  .findOne({ filter: { id: paymentRequestId } })
              : undefined;
          if (!writePolicy || writePolicy.update === false || !writable)
            throw new PaymentAttachmentError(
              'PAYMENT_ATTACHMENT_DENIED',
              'No payment submission permission covers this draft.',
            );
        }
        // Unselected draft uploads are visible only to the people editing that draft. After submit,
        // participants may access only the immutable document's selected attachment IDs.
        const ids =
          (purpose === 'invoice' &&
            ['draft', 'revision'].includes(record.status) &&
            [record.applicantId, record.createdById].includes(actorId)) ||
          (purpose === 'voucher' && record.canViewUnselectedVoucher)
            ? undefined
            : purpose === 'invoice'
              ? record.attachments
              : record.voucherAttachments;
        if (fileId && ids && !ids.includes(fileId))
          throw new PaymentAttachmentError(
            'PAYMENT_ATTACHMENT_DENIED',
            'This attachment is not linked to the submitted payment request.',
          );
        principals.set(c, {
          paymentRequestId,
          actorId,
          version: record.lifecycleVersion,
          purpose,
          upload,
          ids,
        });
        await next();
      });
      if (contribution.scope === 'api') {
        // Limit before validation. Inspect a clone so the generated handler keeps its own
        // multipart parser and body limiter; consuming Hono's request first locks its stream.
        router.use(
          '/paymentAttachments/uploadOne',
          bodyLimit({
            maxSize: MAX_PAYMENT_FILE_SIZE + 65536,
            onError: () => {
              throw new PaymentAttachmentError(
                'PAYMENT_FILE_SIZE',
                'Attachment request is too large.',
              );
            },
          }),
        );
        router.use('/paymentAttachments/uploadOne', async (c, next) => {
          const body = await c.req.raw.clone().formData();
          const files = body.getAll('file');
          if (files.length !== 1 || !(files[0] instanceof File))
            throw new PaymentAttachmentError(
              'PAYMENT_ATTACHMENT_INVALID',
              'Exactly one file is required.',
            );
          await validatePaymentFile(files[0]);
          await next();
        });
      }
      const generatedRouter = await contribution.createRouter(app);
      generatedRouter.onError((error, c) =>
        apiErrorHandler(
          error instanceof PaymentAttachmentError
            ? new ApiError({
                status:
                  error.code === 'PAYMENT_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : 'INVALID_ARGUMENT',
                domain: 'payment',
                reason: error.code,
                message: error.message,
              })
            : error,
          c,
        ),
      );
      router.route('/', generatedRouter);
      const root = new Hono();
      root.route('/', router);
      return root;
    },
  }));
export default routes;
