import { attachmentSelectionFilters } from '../attachment-selection.js';
import {
  authenticationToken,
  type AuthEnv,
} from '@nocobase/app-plugin-authentication';
import {
  authorizationToken,
  type AuthorizationEnv,
} from '@nocobase/app-plugin-authorization/server';
import { defineFileRepositoryApiRoutes } from '@nocobase/app-plugin-file/server';
import { databaseManagerToken } from '@nocobase/db';
import type { Application } from '@nocobase/app-server/application';
import {
  ApiError,
  apiErrorHandler,
  apiValidator,
  type AppRouteContribution,
} from '@nocobase/app-server/router';
import { Hono } from 'hono';
import { bodyLimit } from 'hono/body-limit';
import { z } from 'zod';
import {
  attendanceChangeAttachmentServiceToken,
  AttendanceChangeAttachmentError,
  ATTENDANCE_CHANGE_FILE_FIELDS,
  MAX_ATTENDANCE_CHANGE_FILE_SIZE,
  validateAttendanceChangeFile,
} from '../../providers/attendance-change-attachments/index.js';

type Env = AuthEnv & AuthorizationEnv;
interface Principal {
  attendanceChangeId: string;
  actorId: string;
  version: number;
  ids?: string[];
  upload: boolean;
}
const principals = new WeakMap<object, Principal>();
const generated = defineFileRepositoryApiRoutes<Principal>({
  principal: (c) => principals.get(c)!,
  repositories: [
    {
      name: 'attendanceChangeAttachments',
      collection: 'attendanceChangeAttachmentFiles',
      disk: 'local',
      accessPath: '/uploads/attendanceChange',
      accessMode: 'stream',
      policy: (p) => ({
        read: {
          scope: (f) =>
            f.and([
              f.string('attendanceChangeId').eq(p.attendanceChangeId),
              ...attachmentSelectionFilters(f, p.ids),
            ]),
          fields: ATTENDANCE_CHANGE_FILE_FIELDS,
        },
        create: p.upload
          ? {
              scope: {
                attendanceChangeId: p.attendanceChangeId,
                ownerId: p.actorId,
              },
              defaults: {
                attendanceChangeId: p.attendanceChangeId,
                ownerId: p.actorId,
                uploadVersion: p.version,
              },
            }
          : false,
        update: false,
        delete: false,
      }),
      actions: {
        findMany: { maxLimit: 10 },
        findOne: {},
        uploadOne: { maxSize: MAX_ATTENDANCE_CHANGE_FILE_SIZE + 65536 },
      },
    },
  ],
});

/** Export only these guarded contributions; the generated byte routes are public until wrapped. */
export const routes: readonly AppRouteContribution<Application>[] =
  generated.map((contribution) => ({
    scope: contribution.scope,
    createRouter: async (app: Application) => {
      const router = new Hono<Env>();
      const path =
        contribution.scope === 'api'
          ? '/attendanceChangeAttachments/*'
          : '/uploads/attendanceChange/*';
      const auth = app.container.resolve(authenticationToken);
      const authz = app.container.resolve(authorizationToken);
      const db = app.container.resolve(databaseManagerToken);
      const service = app.container.resolve(
        attendanceChangeAttachmentServiceToken,
      );
      router.onError((error, c) =>
        apiErrorHandler(
          error instanceof AttendanceChangeAttachmentError
            ? new ApiError({
                status:
                  error.code === 'ATTENDANCE_CHANGE_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : 'INVALID_ARGUMENT',
                domain: 'attendanceChange',
                reason: error.code,
                message: error.message,
              })
            : error,
          c,
        ),
      );
      router.use(path, auth.required(), authz.middleware());
      if (contribution.scope === 'api')
        router.use(
          path,
          apiValidator(
            'header',
            z.object({
              'x-attendance-change-request-id': z
                .string()
                .regex(/^[A-Za-z0-9_-]{1,64}$/)
                .describe(
                  'Owning attendanceChange draft or request. All uploads and reads enforce its business permissions.',
                ),
            }),
          ),
        );
      router.use(path, async (c, next) => {
        const actorId = c.get('auth')!.user.id;
        const upload =
          contribution.scope === 'api' && c.req.path.endsWith('/uploadOne');
        let attendanceChangeId = c.req.header('x-attendance-change-request-id');
        let fileId: string | undefined;
        if (contribution.scope === 'root') {
          fileId = c.req.path.split('/').at(-1)?.split('.')[0];
          const file = fileId
            ? await db
                .repository<{ id: string; attendanceChangeId: string }>(
                  'attendanceChangeAttachmentFiles',
                )
                .findOne({ filter: { id: fileId } })
            : undefined;
          if (!file)
            throw new AttendanceChangeAttachmentError(
              'ATTENDANCE_CHANGE_ATTACHMENT_DENIED',
              'The attachment is not accessible.',
            );
          attendanceChangeId = file.attendanceChangeId;
        }
        if (
          !attendanceChangeId ||
          !/^[A-Za-z0-9_-]{1,64}$/.test(attendanceChangeId)
        )
          throw new AttendanceChangeAttachmentError(
            'ATTENDANCE_CHANGE_ATTACHMENT_INVALID',
            'x-attendance-change-request-id must identify the owning draft or request.',
          );
        const decision = await c.get('authz').authorize({
          resource: { type: 'composite', id: 'oa.attendanceChange' },
          action: 'view',
        });
        const policy =
          decision.effect !== 'deny'
            ? decision.conditions?.database?.attendanceChangeRequests
            : undefined;
        if (!policy)
          throw new AttendanceChangeAttachmentError(
            'ATTENDANCE_CHANGE_ATTACHMENT_DENIED',
            'No attendanceChange reading permission is granted.',
          );
        const record = await service.authorize(
          attendanceChangeId,
          actorId,
          policy,
          upload,
        );
        if (upload) {
          const action = record.applicantId === actorId ? 'submit' : 'delegate';
          const write = await c.get('authz').authorize({
            resource: { type: 'composite', id: 'oa.attendanceChange' },
            action,
          });
          const writePolicy =
            write.effect !== 'deny'
              ? write.conditions?.database?.attendanceChangeRequests
              : undefined;
          const update = writePolicy?.update;
          const writable =
            writePolicy &&
            update &&
            (update === true ||
              (Array.isArray(update.fields) &&
                update.fields.includes('attachments')))
              ? await db
                  .repository('attendanceChangeRequests')
                  .withPolicy({
                    ...writePolicy,
                    read:
                      update === true
                        ? true
                        : { scope: update.scope, fields: ['id'] },
                  })
                  .findOne({ filter: { id: attendanceChangeId } })
              : undefined;
          if (!writePolicy || writePolicy.update === false || !writable)
            throw new AttendanceChangeAttachmentError(
              'ATTENDANCE_CHANGE_ATTACHMENT_DENIED',
              'No attendanceChange submission permission covers this draft.',
            );
        }
        // Unselected draft uploads are visible only to the people editing that draft. After submit,
        // participants may access only the immutable document's selected attachment IDs.
        const ids =
          ['draft', 'revision'].includes(record.status) &&
          [record.applicantId, record.createdById].includes(actorId)
            ? undefined
            : record.attachments;
        if (fileId && ids && !ids.includes(fileId))
          throw new AttendanceChangeAttachmentError(
            'ATTENDANCE_CHANGE_ATTACHMENT_DENIED',
            'This attachment is not linked to the submitted attendanceChange request.',
          );
        principals.set(c, {
          attendanceChangeId,
          actorId,
          version: record.lifecycleVersion,
          upload,
          ids,
        });
        await next();
      });
      if (contribution.scope === 'api') {
        // Limit before validation. Inspect a clone so the generated handler keeps its own
        // multipart parser and body limiter; consuming Hono's request first locks its stream.
        router.use(
          '/attendanceChangeAttachments/uploadOne',
          bodyLimit({
            maxSize: MAX_ATTENDANCE_CHANGE_FILE_SIZE + 65536,
            onError: () => {
              throw new AttendanceChangeAttachmentError(
                'ATTENDANCE_CHANGE_FILE_SIZE',
                'Attachment request is too large.',
              );
            },
          }),
        );
        router.use(
          '/attendanceChangeAttachments/uploadOne',
          async (c, next) => {
            const body = await c.req.raw.clone().formData();
            const files = body.getAll('file');
            if (files.length !== 1 || !(files[0] instanceof File))
              throw new AttendanceChangeAttachmentError(
                'ATTENDANCE_CHANGE_ATTACHMENT_INVALID',
                'Exactly one file is required.',
              );
            await validateAttendanceChangeFile(files[0]);
            await next();
          },
        );
      }
      const generatedRouter = await contribution.createRouter(app);
      generatedRouter.onError((error, c) =>
        apiErrorHandler(
          error instanceof AttendanceChangeAttachmentError
            ? new ApiError({
                status:
                  error.code === 'ATTENDANCE_CHANGE_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : 'INVALID_ARGUMENT',
                domain: 'attendanceChange',
                reason: error.code,
                message: error.message,
              })
            : error,
          c,
        ),
      );
      router.route('/', generatedRouter);
      const root = new Hono();
      root.route('/', router);
      return root;
    },
  }));
export default routes;
