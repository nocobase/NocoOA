import { attachmentSelectionFilters } from '../attachment-selection.js';
import { purchaseQuoteBasis } from '../../providers/purchases/quotes.js';
import {
  authenticationToken,
  type AuthEnv,
} from '@nocobase/app-plugin-authentication';
import {
  authorizationToken,
  type AuthorizationEnv,
} from '@nocobase/app-plugin-authorization/server';
import { defineFileRepositoryApiRoutes } from '@nocobase/app-plugin-file/server';
import { databaseManagerToken } from '@nocobase/db';
import type { Application } from '@nocobase/app-server/application';
import {
  ApiError,
  apiErrorHandler,
  apiValidator,
  type AppRouteContribution,
} from '@nocobase/app-server/router';
import { Hono } from 'hono';
import { bodyLimit } from 'hono/body-limit';
import { z } from 'zod';
import {
  purchaseAttachmentServiceToken,
  PurchaseAttachmentError,
  PURCHASE_FILE_FIELDS,
  MAX_PURCHASE_FILE_SIZE,
  validatePurchaseFile,
} from '../../providers/purchases/index.js';

type Env = AuthEnv & AuthorizationEnv;
interface Principal {
  purchaseId: string;
  actorId: string;
  vendorId?: string;
  version: number;
  quoteBasisHash: string;
  ids?: string[];
  upload: boolean;
}
const principals = new WeakMap<object, Principal>();
const generated = defineFileRepositoryApiRoutes<Principal>({
  principal: (c) => principals.get(c)!,
  repositories: [
    {
      name: 'purchaseAttachments',
      collection: 'purchaseQuoteFiles',
      disk: 'local',
      accessPath: '/uploads/purchase',
      accessMode: 'stream',
      policy: (p) => ({
        read: {
          scope: (f) =>
            f.and([
              f.string('purchaseId').eq(p.purchaseId),
              ...attachmentSelectionFilters(f, p.ids),
            ]),
          fields: PURCHASE_FILE_FIELDS,
        },
        create: p.upload
          ? {
              scope: {
                purchaseId: p.purchaseId,
                vendorId: p.vendorId!,
                ownerId: p.actorId,
              },
              defaults: {
                purchaseId: p.purchaseId,
                vendorId: p.vendorId!,
                ownerId: p.actorId,
                uploadVersion: p.version,
                quoteBasisHash: p.quoteBasisHash,
              },
            }
          : false,
        update: false,
        delete: false,
      }),
      actions: {
        findMany: { maxLimit: 100 },
        findOne: {},
        uploadOne: { maxSize: MAX_PURCHASE_FILE_SIZE + 65536 },
      },
    },
  ],
});

/** Export only these guarded contributions; the generated byte routes are public until wrapped. */
export const routes: readonly AppRouteContribution<Application>[] =
  generated.map((contribution) => ({
    scope: contribution.scope,
    createRouter: async (app: Application) => {
      const router = new Hono<Env>();
      const path =
        contribution.scope === 'api'
          ? '/purchaseAttachments/*'
          : '/uploads/purchase/*';
      const auth = app.container.resolve(authenticationToken);
      const authz = app.container.resolve(authorizationToken);
      const db = app.container.resolve(databaseManagerToken);
      const service = app.container.resolve(purchaseAttachmentServiceToken);
      router.onError((error, c) =>
        apiErrorHandler(
          error instanceof PurchaseAttachmentError
            ? new ApiError({
                status:
                  error.code === 'PURCHASE_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : error.code === 'PURCHASE_ATTACHMENT_VERSION_CONFLICT'
                      ? 'ABORTED'
                      : 'INVALID_ARGUMENT',
                domain: 'purchase',
                reason: error.code,
                message: error.message,
              })
            : error,
          c,
        ),
      );
      router.use(path, auth.required(), authz.middleware());
      if (contribution.scope === 'api')
        router.use(
          path,
          apiValidator(
            'header',
            z.object({
              'x-purchase-version': z
                .string()
                .regex(/^\d+$/)
                .optional()
                .describe(
                  'Required for uploads: the lifecycle version displayed to the current handler.',
                ),
              'x-purchase-quote-basis': z
                .string()
                .regex(/^[a-f0-9]{64}$/)
                .optional()
                .describe(
                  'Required for uploads: the immutable requirements basis displayed with the quote form.',
                ),
              'x-purchase-vendor-id': z
                .string()
                .regex(/^[A-Za-z0-9_-]{1,64}$/)
                .optional(),
              'x-purchase-request-id': z
                .string()
                .regex(/^[A-Za-z0-9_-]{1,64}$/)
                .describe(
                  'Owning purchase draft or request. All uploads and reads enforce its business permissions.',
                ),
            }),
          ),
        );
      router.use(path, async (c, next) => {
        const actorId = c.get('auth')!.user.id;
        const upload =
          contribution.scope === 'api' && c.req.path.endsWith('/uploadOne');
        let purchaseId = c.req.header('x-purchase-request-id');
        const vendorId = c.req.header('x-purchase-vendor-id');
        if (upload && (!vendorId || !/^[A-Za-z0-9_-]{1,64}$/.test(vendorId)))
          throw new PurchaseAttachmentError(
            'PURCHASE_ATTACHMENT_INVALID',
            'Choose an active quote vendor.',
          );
        let fileId: string | undefined;
        if (contribution.scope === 'root') {
          fileId = c.req.path.split('/').at(-1)?.split('.')[0];
          const file = fileId
            ? await db
                .repository<{ id: string; purchaseId: string }>(
                  'purchaseQuoteFiles',
                )
                .findOne({ filter: { id: fileId } })
            : undefined;
          if (!file)
            throw new PurchaseAttachmentError(
              'PURCHASE_ATTACHMENT_DENIED',
              'The attachment is not accessible.',
            );
          purchaseId = file.purchaseId;
        }
        if (!purchaseId || !/^[A-Za-z0-9_-]{1,64}$/.test(purchaseId))
          throw new PurchaseAttachmentError(
            'PURCHASE_ATTACHMENT_INVALID',
            'x-purchase-request-id must identify the owning draft or request.',
          );
        const decision = await c.get('authz').authorize({
          resource: { type: 'composite', id: 'oa.purchase' },
          action: 'view',
        });
        const policy =
          decision.effect !== 'deny'
            ? decision.conditions?.database?.purchaseRequests
            : undefined;
        if (!policy)
          throw new PurchaseAttachmentError(
            'PURCHASE_ATTACHMENT_DENIED',
            'No purchase reading permission is granted.',
          );
        const record = await service.authorize(
          purchaseId,
          vendorId,
          actorId,
          policy,
          upload,
        );
        if (upload) {
          const requestedVersion = c.req.header('x-purchase-version');
          if (
            !requestedVersion ||
            !/^\d+$/.test(requestedVersion) ||
            !Number.isSafeInteger(Number(requestedVersion))
          )
            throw new PurchaseAttachmentError(
              'PURCHASE_ATTACHMENT_INVALID',
              'A displayed lifecycle version is required for quote uploads.',
            );
          if (Number(requestedVersion) !== record.lifecycleVersion)
            throw new PurchaseAttachmentError(
              'PURCHASE_ATTACHMENT_VERSION_CONFLICT',
              'The purchasing task changed. Refresh the request before uploading evidence.',
            );
          if (
            c.req.header('x-purchase-quote-basis') !==
            purchaseQuoteBasis(record)
          )
            throw new PurchaseAttachmentError(
              'PURCHASE_ATTACHMENT_INVALID',
              'The procurement requirements changed. Refresh the request before uploading evidence.',
            );
        }
        // Selected quotations belong to the immutable approval. During purchasing the uploader may
        // also read their unselected evidence; later transitions never expose unused files to others.
        const selected = record.quotes.flatMap((q) => q.attachmentIds);
        const own =
          record.status === 'purchasing'
            ? await db
                .repository<{
                  id: string;
                  purchaseId: string;
                  ownerId: string;
                }>('purchaseQuoteFiles')
                .findMany({ filter: { purchaseId, ownerId: actorId } })
            : [];
        const ids = [...new Set([...selected, ...own.map((f) => f.id)])];
        if (fileId && ids && !ids.includes(fileId))
          throw new PurchaseAttachmentError(
            'PURCHASE_ATTACHMENT_DENIED',
            'This attachment is not linked to the submitted purchase request.',
          );
        principals.set(c, {
          purchaseId,
          vendorId,
          actorId,
          version: record.lifecycleVersion,
          quoteBasisHash: purchaseQuoteBasis(record),
          upload,
          ids,
        });
        await next();
      });
      if (contribution.scope === 'api') {
        // Limit before validation. Inspect a clone so the generated handler keeps its own
        // multipart parser and body limiter; consuming Hono's request first locks its stream.
        router.use(
          '/purchaseAttachments/uploadOne',
          bodyLimit({
            maxSize: MAX_PURCHASE_FILE_SIZE + 65536,
            onError: () => {
              throw new PurchaseAttachmentError(
                'PURCHASE_FILE_SIZE',
                'Attachment request is too large.',
              );
            },
          }),
        );
        router.use('/purchaseAttachments/uploadOne', async (c, next) => {
          const body = await c.req.raw.clone().formData();
          const files = body.getAll('file');
          if (files.length !== 1 || !(files[0] instanceof File))
            throw new PurchaseAttachmentError(
              'PURCHASE_ATTACHMENT_INVALID',
              'Exactly one file is required.',
            );
          await validatePurchaseFile(files[0]);
          await next();
        });
      }
      const generatedRouter = await contribution.createRouter(app);
      generatedRouter.onError((error, c) =>
        apiErrorHandler(
          error instanceof PurchaseAttachmentError
            ? new ApiError({
                status:
                  error.code === 'PURCHASE_ATTACHMENT_DENIED'
                    ? 'PERMISSION_DENIED'
                    : error.code === 'PURCHASE_ATTACHMENT_VERSION_CONFLICT'
                      ? 'ABORTED'
                      : 'INVALID_ARGUMENT',
                domain: 'purchase',
                reason: error.code,
                message: error.message,
              })
            : error,
          c,
        ),
      );
      router.route('/', generatedRouter);
      const root = new Hono();
      root.route('/', router);
      return root;
    },
  }));
export default routes;
